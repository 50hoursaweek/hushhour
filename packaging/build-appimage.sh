#!/usr/bin/env bash
# Build dist/HushHour-x86_64.AppImage from a release build.
# Requires appimagetool on PATH or APPIMAGETOOL pointing at it.
set -euo pipefail
cd "$(dirname "$0")/.."

cargo build --release
APPDIR=target/AppDir
rm -rf "$APPDIR"
mkdir -p "$APPDIR/usr/bin" "$APPDIR/usr/share/applications" \
         "$APPDIR/usr/share/icons/hicolor/256x256/apps" \
         "$APPDIR/usr/share/icons/hicolor/512x512/apps" \
         "$APPDIR/usr/share/icons/hicolor/scalable/apps"

cp target/release/hushhour "$APPDIR/usr/bin/hushhour"
ID=io.github._50hoursaweek.hushhour
cp "packaging/$ID.desktop" "$APPDIR/$ID.desktop"
cp "packaging/$ID.desktop" "$APPDIR/usr/share/applications/$ID.desktop"
mkdir -p "$APPDIR/usr/share/metainfo"
cp "packaging/$ID.metainfo.xml" "$APPDIR/usr/share/metainfo/$ID.metainfo.xml"
cp assets/icon-256.png "$APPDIR/usr/share/icons/hicolor/256x256/apps/$ID.png"
cp assets/icon-512.png "$APPDIR/usr/share/icons/hicolor/512x512/apps/$ID.png"
cp assets/hushhour-icon.svg "$APPDIR/usr/share/icons/hicolor/scalable/apps/$ID.svg"
# Optional bundled music (assets/music, not tracked), found by the app relative to the executable.
if compgen -G "assets/music/*.*" >/dev/null; then
  mkdir -p "$APPDIR/usr/share/hushhour/music"
  cp assets/music/*.* "$APPDIR/usr/share/hushhour/music/"
fi
cp assets/icon-256.png "$APPDIR/$ID.png"
cp assets/icon-256.png "$APPDIR/.DirIcon"
# Licence and credit texts, reachable from the About dialog.
LIC="$APPDIR/usr/share/licenses/hushhour"
mkdir -p "$LIC/fonts" "$LIC/sounds"
cp LICENSE "$LIC/LICENSE"
cp packaging/LICENSE-iced.txt "$LIC/LICENSE-iced.txt"
cp assets/fonts/LICENSE-*.txt assets/fonts/LICENSE-Lato.md assets/fonts/README.md "$LIC/fonts/"
cp assets/sounds/README.md "$LIC/sounds/README.md"
printf 'The music loops in share/hushhour/music were generated by the author with Google Lyria 3\nand are dedicated to the public domain under CC0 1.0.\n' > "$LIC/MUSIC-CC0.txt"
ln -sf usr/bin/hushhour "$APPDIR/AppRun"

mkdir -p dist
# Build to a temporary name and rename over the old one, so packaging works
# while a previous AppImage is still running (overwriting it in place fails
# with "Text file busy").
OUT=dist/HushHour-x86_64.AppImage
# Only x86_64 is built and tested; refuse to mislabel another architecture.
[ "$(uname -m)" = x86_64 ] || { echo "build-appimage.sh: only x86_64 is supported (host is $(uname -m))" >&2; exit 1; }
ARCH=x86_64 "${APPIMAGETOOL:-appimagetool}" --no-appstream "$APPDIR" "$OUT.tmp"
mv -f "$OUT.tmp" "$OUT"
ls -la "$OUT"
